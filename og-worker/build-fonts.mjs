// Regenerates og-worker/src/fonts.generated.ts from og-worker/fonts/*.ttf.
// Fonts are static, Latin-subset instances of Newsreader (opsz 48, wght 400)
// and Figtree (400/600), both OFL. Embedded as base64 so the Worker needs no
// asset fetch to render share cards.
import { readFileSync, writeFileSync } from "node:fs";
const fonts = { newsreader400: "newsreader-400.ttf", figtree400: "figtree-400.ttf", figtree600: "figtree-600.ttf" };
let out = "// Generated by og-worker/build-fonts.mjs — do not edit.\n";
for (const [k, f] of Object.entries(fonts)) {
  const b64 = readFileSync(new URL(`./fonts/${f}`, import.meta.url)).toString("base64");
  out += `export const ${k} = "${b64}";\n`;
}
writeFileSync(new URL("./src/fonts.generated.ts", import.meta.url), out);
